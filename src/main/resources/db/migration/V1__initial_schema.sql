-- Schema as it was created by Hibernate before Flyway was introduced.
-- Existing databases are baselined at version 1 (see quarkus.flyway.baseline-*),
-- so this script only runs on an empty database.

CREATE TABLE category (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL
);

CREATE TABLE tag (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL
);

CREATE TABLE entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checkIn     TIMESTAMP(6) NOT NULL,
    checkOut    TIMESTAMP(6) NOT NULL,
    category_id BIGINT REFERENCES category (id)
);

CREATE TABLE entry_tag (
    entry_id BIGINT NOT NULL REFERENCES entry (id),
    tag_id   BIGINT NOT NULL REFERENCES tag (id),
    PRIMARY KEY (entry_id, tag_id)
);

CREATE TABLE application_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL UNIQUE,
    passwordHash VARCHAR(255) NOT NULL,
    role         VARCHAR(255) NOT NULL
);
